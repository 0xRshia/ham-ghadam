import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = ts.transpileModule(readFileSync(new URL('../lib/squirrel-ar-camera.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {rearCameras,prepareArCamera,bindArCamera} = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const device = (deviceId,label) => ({kind:'videoinput',deviceId,label});
const lenses = [device('ultra','Back Ultra Wide Camera'),device('front','Front Camera'),device('tele','Back Telephoto Camera'),device('dual','Back Dual Wide Camera'),device('main','Back Camera')];
assert.equal(rearCameras(lenses,'ultra')[0].deviceId,'main');
assert.equal(rearCameras([device('ultra','Back Ultra Wide Camera'),device('wide','Back Wide Angle Camera')],'ultra')[0].deviceId,'wide');
assert.equal(rearCameras([device('other','camera2 2, facing back'),device('zero','camera2 0, facing back')])[0].deviceId,'zero');
assert.equal(rearCameras(lenses).some(camera => camera.deviceId === 'front'),false);
assert.equal(rearCameras([device('opaque','')],'opaque')[0].deviceId,'opaque');
let stopped = 0, requested;
const stream = id => ({getTracks:()=>[{stop(){stopped++;}}],getVideoTracks:()=>[{getSettings:()=>({deviceId:id})}]});
const media = {async getUserMedia(constraints){requested=constraints;return stream(constraints.video.deviceId?.exact ?? 'ultra');},async enumerateDevices(){return lenses;}};
const original = media.getUserMedia;
const choice = await prepareArCamera(undefined,new AbortController().signal,media);
assert.equal(choice.selected.deviceId,'main'); assert.equal(stopped,1,'The permission probe releases its camera');
assert.equal((await prepareArCamera('tele',new AbortController().signal,media)).selected.deviceId,'tele');
const dispose = bindArCamera('main',media);
await media.getUserMedia({video:{facingMode:{exact:'environment'},width:{exact:640}}});
assert.deepEqual(requested.video.deviceId,{exact:'main'});
assert.equal(requested.video.facingMode,undefined);
assert.deepEqual(requested.video.width,{exact:640},'Preserve SDK capture dimensions');
dispose(); assert.equal(media.getUserMedia,original);
const controller = new AbortController();
const delayed = {getUserMedia:async () => {controller.abort();return stream('main');},enumerateDevices:async()=>lenses};
await assert.rejects(prepareArCamera(undefined,controller.signal,delayed),{name:'AbortError'});
let release;
const pendingMedia = {getUserMedia:()=>new Promise(resolve=>{release=resolve;})};
const end = bindArCamera('main',pendingMedia);
const pending = pendingMedia.getUserMedia({video:true});
end(); const before=stopped; release(stream('main'));
await assert.rejects(pending,{name:'AbortError'}); assert.equal(stopped,before+1,'Late camera streams are stopped after cancellation');
const incorrect = {async getUserMedia(){return stream('ultra');}};
const unbind = bindArCamera('main',incorrect);
await assert.rejects(incorrect.getUserMedia({video:true}),{name:'NotReadableError'}); unbind();
console.log('AR cameras: physical main lens ranking, explicit override, exact device constraints, probe cleanup, API restoration, late cancellation and wrong-lens rejection passed.');
