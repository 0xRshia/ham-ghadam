import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const source = ts.transpileModule(fs.readFileSync("lib/catalog-store.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { createCatalogStore } = await import(`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`);
let time = 1000;
const requests = [];
const store = createCatalogStore(() => new Promise((resolve, reject) => requests.push({ resolve, reject })), () => time);
const catalog = viewerId => ({ events: [], suggestions: [], viewerId, serverNow: time });
const first = store.refresh();
assert.equal(store.refresh(), first, "Simultaneous readers share one request");
store.identify(null);
requests[0].resolve(catalog(null)); await first;
await store.refresh(); assert.equal(requests.length, 1);
time += 60000;
const refreshed = store.refresh();
assert.ok(store.getSnapshot().catalog, "Keep visible data while refreshing");
requests[1].reject(new Error("offline")); await refreshed;
assert.equal(store.getSnapshot().error, "offline");
assert.ok(store.getSnapshot().catalog);
const stale = store.refresh(true);
store.invalidate(); store.identify("new-account");
const account = store.refresh();
requests[2].resolve(catalog(null)); await stale;
assert.equal(store.getSnapshot().catalog, null, "Late responses cannot cross authentication generations");
requests[3].resolve(catalog("new-account")); await account;
assert.equal(store.getSnapshot().catalog.viewerId, "new-account");
store.identify(null);
assert.equal(store.getSnapshot().catalog, null, "Account change removes personalized results immediately");
const mismatch = store.refresh();requests[4].resolve(catalog("old-account"));await mismatch;
assert.equal(store.getSnapshot().catalog, null);
assert.ok(store.getSnapshot().error, "Session mismatch is surfaced, never silently cached");
const retry = store.refresh(true);requests[5].resolve(catalog(null));await retry;
assert.equal(store.getSnapshot().error, "");
assert.equal(store.getServerSnapshot().catalog, null, "SSR never receives browser cached data");
console.log("PASS catalog deduplication, freshness, retained data, retries, identity and generation isolation");
