import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const source=ts.transpileModule(readFileSync(new URL('../lib/squirrel-ar-floor.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {estimateFloor,emptyFloorLock,updateFloorLock,floorSettleTime}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const camera={x:0,y:1.5,z:0}, ground={x:0,y:0,z:-2};
const surface={type:'ESTIMATED_SURFACE',position:ground,rotation:{x:0,y:0,z:0,w:1},distance:2.5};
assert.deepEqual(estimateFloor([surface],[],camera).position,ground);
assert.equal(estimateFloor([{...surface,type:'FEATURE_POINT'}],[],camera),null,'An isolated feature is not floor detection');
assert.equal(estimateFloor([{...surface,rotation:{x:Math.SQRT1_2,y:0,z:0,w:Math.SQRT1_2}}],[],camera),null,'Reject vertical surfaces');
assert.equal(estimateFloor([{...surface,position:{...ground,y:1.4}}],[],camera),null,'Reject geometry at camera height');
assert.equal(estimateFloor([{...surface,position:{...ground,y:2}}],[],camera),null,'Reject ceilings');
assert.equal(estimateFloor([{...surface,distance:NaN}],[],camera),null);
assert.equal(estimateFloor([{...surface,rotation:{x:0,y:0,z:0,w:0}}],[],camera),null,'Uninitialized orientation cannot qualify as a floor');
const cloud=Array.from({length:16},(_,i)=>({confidence:1,position:{x:(i%4)*.22-.33,y:.01*(i%2),z:-2+Math.floor(i/4)*.22-.33}}));
assert.equal(estimateFloor([],cloud,camera).source,'points');
assert.equal(estimateFloor([],cloud.slice(0,2),camera),null,'Sparse points cannot establish a floor');
const wallLine=cloud.map((p,i)=>({...p,position:{x:i*.1-.8,y:0,z:i*.1-2}}));
assert.equal(estimateFloor([],wallLine,camera),null,'A horizontal line on a diagonal wall is not a floor patch');
let lock=emptyFloorLock();
for(let t=0;t<floorSettleTime;t+=100) lock=updateFloorLock(lock,ground,100,true);
assert.ok(lock.stableMs < floorSettleTime,'First hit alone cannot complete the settling timer');
lock=updateFloorLock(lock,ground,100,true);assert.equal(lock.stableMs,floorSettleTime);
assert.deepEqual(updateFloorLock(lock,null,150,true).point,ground,'Preserve a stable position through brief misses');
assert.deepEqual(updateFloorLock(lock,ground,100,false),emptyFloorLock(),'Losing tracking resets confidence');
for(let i=0;i<7;i++) lock=updateFloorLock(lock,null,100,true);
assert.deepEqual(lock.point,null,'Long gaps invalidate a stale floor');
lock=updateFloorLock({point:ground,stableMs:800,missingMs:0},{...ground,y:.3},100,true);
assert.equal(lock.stableMs,0,'A changed plane must settle again');
console.log('Automatic floor: horizontal surfaces, broad point-cloud support, wall/ceiling/isolated-point rejection, settling timer, miss tolerance and tracking-loss reset passed.');
